// The three overworlds, one before each dungeon: the round clearings the player walks between the
// dungeons in. Each is the same every run (only the dungeons are random). The first is where the
// run starts; the player comes into the next one through the boss room's door of the dungeon
// before it, standing on its @. From an overworld the player walks into its dungeon or into a
// house, and the camera follows them across it (see camera.js).
//
// Legend
//   #  forest (wall). The clearing is drawn as a circle with # all around it.
//   .  grass     x  a tree or rock (an obstacle)     @  where the player starts (exactly one)
//   D  a dungeon entrance. Each touching group of D is one entrance; walking onto it goes in.
//   h  the roof and walls of a house (solid)
//   1-9  a house's door. Two side by side, in the house's bottom row. The digit says which house
//      in the houses list below it opens, so the digit has to match that house's id.
//   The tile just south of every entrance and house door must be grass: that is where the player
//   stands when they come back out.
// theme ("meadow", "autumn" or "ashen") picks the colors the view draws the overworld in.
// Every row must be the same length, the outer ring must be all #, and the grass must be in one
// piece. validateOverworldTemplate() checks all of it, and the specs run it.
//
// npcs: { name, col, row, dialogue: [pages] } stands on grass at that tile, and talks when the
// player presses Space or F next to it. Houses have their own npcs, with col and row inside the house.
