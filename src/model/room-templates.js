// The pre-made rooms. The dungeon generator picks from this list, so every room in a run
// is one of these. The drawing decides the room's size AND where its doors are.
//
// To add a room: copy one block, give it a new name, and draw it. Every row must be the
// same length, and the outer ring must be all # except for the doors.
//
// Legend
//   #  wall            .  floor           o  pit        x  interior wall (an obstacle)
//   +  a door (on the outer wall only, always 2 tiles side by side)
//   m  a melee spot: a chaser or swarm enemy may start here
//   r  a ranged spot: a shooter or turret may start here (behind cover, or far from the doors)
//   J  Jelly   Z  Zombie   S  Skeleton   B  Bat   E  Eyeball   D  Demon (fixed enemy, on floor)
//   C  a treasure chest (on floor; press E next to it to open)
//   K  Bouncer (a knight, 32x32)   T  Spark Bark (a tree, a stationary turret)
//   @  where the player starts (start rooms only, exactly one)
//
// Normal rooms do not draw their enemies. encounters.js picks a seeded mix of enemies for each
// wave and puts them on the m and r spots (shooters on r, the rest on m). Draw at least 4 m and
// 3 r, away from the doors. Enemy letters still work for a fixed placement, and a boss room
// draws its boss (and any adds) with letters.
//
// Size: normal and treasure rooms are one of three sizes, walls included, so the whole room
// always fits the screen: small 22x13, medium 28x17, large 36x21. Start and boss rooms may use
// any size up to 40x22. See ROOM_SIZE_CLASSES in template-room.js.
//
// Walls can also stick out of the outer wall into the room, drawn with more #. They have wall
// art with sloped corners, so each one must be at least 2 tiles thick. Use x for anything thinner.
// Pits (o) are a drop: the player falls in and respawns at the door they came in through, and an
// enemy that is knocked over one dies. Leave a way round or across them, since the floor has to
// stay in one piece.
//
// Doors: draw as many as you like, on any wall. A door only opens when another room is placed
// against it with a matching door straight across; any door that isn't used stays a wall.
// The two tiles just inside a door must be plain floor (.). Doors can't be next to each other.
//
// role: "start" (the first room), "boss" (the last room), "treasure" (a dead end with a chest
// and no enemies), "hub" (the stop between dungeons, see HUB_TEMPLATE) or "normal" (everything
// else). Every room needs at least one door.
// validateRoomTemplates() checks all of this, and the specs run it, so a mistake shows up as
